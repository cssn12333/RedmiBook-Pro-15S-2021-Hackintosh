import getpass, pathlib, plistlib, re, sys, uuid
path=pathlib.Path(sys.argv[1] if len(sys.argv)>1 else 'EFI/OC/config.plist')
config=plistlib.loads(path.read_bytes())
serial=getpass.getpass('SystemSerialNumber (hidden): ').strip()
mlb=getpass.getpass('MLB (hidden): ').strip()
identifier=getpass.getpass('SystemUUID (hidden): ').strip()
rom=getpass.getpass('ROM, 12 hexadecimal digits (hidden): ').strip().replace(':','').replace('-','')
if not re.fullmatch(r'[A-Za-z0-9]{10,12}',serial): raise SystemExit('Invalid serial format')
if not re.fullmatch(r'[A-Za-z0-9]{17}',mlb): raise SystemExit('MLB must contain 17 alphanumeric characters')
try: identifier=str(uuid.UUID(identifier)).upper()
except ValueError: raise SystemExit('Invalid UUID')
if identifier=='00000000-0000-0000-0000-000000000000': raise SystemExit('UUID must not be zero')
if not re.fullmatch(r'[A-Fa-f0-9]{12}',rom) or int(rom,16)==0: raise SystemExit('ROM must contain 12 nonzero hexadecimal digits')
backup=path.with_name(path.name+'.private-backup')
if backup.exists(): raise SystemExit('Existing private backup found; move it before continuing')
backup.write_bytes(path.read_bytes())
config['PlatformInfo']['Generic'].update(SystemSerialNumber=serial,MLB=mlb,SystemUUID=identifier,ROM=bytes.fromhex(rom))
path.write_bytes(plistlib.dumps(config,sort_keys=False))
print('Identity saved locally. Do not publish the personalized config or private backup.')
